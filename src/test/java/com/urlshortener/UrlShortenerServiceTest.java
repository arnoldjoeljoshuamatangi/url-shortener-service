package com.urlshortener;

import com.urlshortener.dto.ShortenRequest;
import com.urlshortener.dto.ShortenResponse;
import com.urlshortener.entity.Url;
import com.urlshortener.repository.ClickAnalyticsRepository;
import com.urlshortener.repository.UrlRepository;
import com.urlshortener.service.UrlService;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.mock.web.MockHttpServletRequest;

import java.util.Optional;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

@ExtendWith(MockitoExtension.class)
class UrlShortenerServiceTest {

    @Mock
    private UrlRepository urlRepository;

    @Mock
    private ClickAnalyticsRepository analyticsRepository;

    @InjectMocks
    private UrlService urlService;

    private MockHttpServletRequest httpServletRequest;

    @BeforeEach
    void setUp() {
        httpServletRequest = new MockHttpServletRequest();
        httpServletRequest.setServerName("localhost");
        httpServletRequest.setServerPort(8080);
        httpServletRequest.setScheme("http");
    }

    @Test
    void testShortenUrl_AutoGeneratedCode() {
        when(urlRepository.existsByShortCode(any())).thenReturn(false);
        when(urlRepository.save(any(Url.class))).thenAnswer(invocation -> invocation.getArgument(0));

        ShortenRequest request = new ShortenRequest("https://google.com", null, null);
        ShortenResponse response = urlService.shortenUrl(request, httpServletRequest);

        assertNotNull(response);
        assertEquals("https://google.com", response.getOriginalUrl());
        assertNotNull(response.getShortCode());
        assertTrue(response.getShortUrl().contains(response.getShortCode()));
        verify(urlRepository, times(1)).save(any(Url.class));
    }

    @Test
    void testShortenUrl_CustomAlias() {
        when(urlRepository.existsByShortCode("custom-promo")).thenReturn(false);
        when(urlRepository.save(any(Url.class))).thenAnswer(invocation -> invocation.getArgument(0));

        ShortenRequest request = new ShortenRequest("https://example.com/promo", "custom-promo", 7);
        ShortenResponse response = urlService.shortenUrl(request, httpServletRequest);

        assertNotNull(response);
        assertEquals("custom-promo", response.getShortCode());
        assertNotNull(response.getExpiresAt());
    }

    @Test
    void testResolveUrlAndTrack() {
        Url mockUrl = new Url("https://example.com/target", "abc1234", null, null);
        when(urlRepository.findByShortCode("abc1234")).thenReturn(Optional.of(mockUrl));

        String resolved = urlService.resolveUrlAndTrack("abc1234", httpServletRequest);

        assertEquals("https://example.com/target", resolved);
        assertEquals(1, mockUrl.getClickCount());
        verify(urlRepository, times(1)).save(mockUrl);
    }
}

